export const ALL_RUSSIAN_CITIES: RussianCityItem[] = COMPACT_RUSSIAN_CITIES.map(
  (line, idx) => {
    const [nameRu, regionRu, latStr, lonStr] = line.split("|");
    return {
      id: `ru_city_${idx}`,
      nameRu,
      regionRu,
      lat: Number(latStr),
      lon: Number(lonStr),
    };
  }
);

const ALADHAN_CITY_STORAGE_KEY = "namaz_aladhan_ru_city_v1";

export function findRussianCityByName(nameRu: string): RussianCityItem | undefined {
  const normalized = nameRu.trim().toLowerCase();
  return ALL_RUSSIAN_CITIES.find((c) => c.nameRu.toLowerCase() === normalized);
}

export function loadSavedAladhanRussianCity(fallbackNameRu = "Уфа"): RussianCityItem {
  try {
    if (typeof window !== "undefined") {
      const raw = window.localStorage.getItem(ALADHAN_CITY_STORAGE_KEY);
      if (raw) {
        const parsed = JSON.parse(raw) as RussianCityItem;
        if (
          parsed &&
          typeof parsed.nameRu === "string" &&
          typeof parsed.lat === "number" &&
          typeof parsed.lon === "number"
        ) {
          return parsed;
        }
      }
    }
  } catch {
    // ignore storage errors
  }
  return (
    findRussianCityByName(fallbackNameRu) ||
    findRussianCityByName("Уфа") ||
    ALL_RUSSIAN_CITIES[0]
  );
}

export function saveAladhanRussianCity(city: RussianCityItem): void {
  try {
    if (typeof window !== "undefined") {
      window.localStorage.setItem(ALADHAN_CITY_STORAGE_KEY, JSON.stringify(city));
    }
  } catch {
    // ignore storage errors
  }
}
