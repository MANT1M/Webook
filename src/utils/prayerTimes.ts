export function parseTimeToMinutes(timeStr: string): number {
  const [hStr, mStr] = timeStr.split(':');
  const h = parseInt(hStr, 10) || 0;
  const m = parseInt(mStr, 10) || 0;
  return h * 60 + m;
}

export function formatMinutesToHHMM(totalMinutes: number): string {
  const normalized = ((Math.round(totalMinutes) % 1440) + 1440) % 1440;
  const h = Math.floor(normalized / 60);
  const m = normalized % 60;
  return `${h}:${String(m).padStart(2, '0')}`;
}

/**
 * Находит индекс строки таблицы, соответствующий сегодняшней дате (или ближайшей дате таблицы).
 */
export function findTodayRowIndex(now: Date): number {
  const month = now.getMonth() + 1;
  const day = now.getDate();
  const exactIdx = PRAYER_SCHEDULE_TABLE.findIndex(
    (r) => r.month === month && r.day === day
  );
  if (exactIdx !== -1) {
    return exactIdx;
  }
  const nov4Idx = PRAYER_SCHEDULE_TABLE.findIndex(
    (r) => r.month === 11 && r.day === 4
  );
  return nov4Idx !== -1 ? nov4Idx : 0;
}

/**
 * Вычисляет текущий период и время до следующего события по выбранной строке таблицы
 */
export function getActiveAndNextPrayerFromRow(
  row: PrayerTableRow,
  nextDayRow: PrayerTableRow,
  now: Date
): {
  activeKey: PrayerKey | null;
  nextKey: PrayerKey;
  nextTimeFormatted: string;
  isTomorrowFajr: boolean;
  secondsRemaining: number;
  progressPercent: number;
} {
  const order: PrayerKey[] = [
    'fajr',
    'sunrise',
    'dhuhr',
    'asr',
    'maghrib',
    'isha',
  ];

  const nowSeconds =
    now.getHours() * 3600 + now.getMinutes() * 60 + now.getSeconds();

  const timesSec: Record<PrayerKey, number> = {
    fajr: parseTimeToMinutes(row.fajr) * 60,
    sunrise: parseTimeToMinutes(row.sunrise) * 60,
    dhuhr: parseTimeToMinutes(row.dhuhr) * 60,
    asr: parseTimeToMinutes(row.asr) * 60,
    maghrib: parseTimeToMinutes(row.maghrib) * 60,
    isha: parseTimeToMinutes(row.isha) * 60,
  };

  if (nowSeconds < timesSec.fajr) {
    const prevIshaSec = parseTimeToMinutes(row.isha) * 60 - 86400;
    const totalSpan = Math.max(1, timesSec.fajr - prevIshaSec);
    const elapsed = nowSeconds - prevIshaSec;
    return {
      activeKey: 'isha',
      nextKey: 'fajr',
      nextTimeFormatted: row.fajr,
      isTomorrowFajr: false,
      secondsRemaining: Math.max(0, timesSec.fajr - nowSeconds),
      progressPercent: Math.min(100, Math.max(0, (elapsed / totalSpan) * 100)),
    };
  }

  for (let i = 0; i < order.length - 1; i++) {
    const currentKey = order[i];
    const nextKey = order[i + 1];
    if (nowSeconds >= timesSec[currentKey] && nowSeconds < timesSec[nextKey]) {
      const span = Math.max(1, timesSec[nextKey] - timesSec[currentKey]);
      const elapsed = nowSeconds - timesSec[currentKey];
      return {
        activeKey: currentKey,
        nextKey,
        nextTimeFormatted: row[nextKey],
        isTomorrowFajr: false,
        secondsRemaining: Math.max(0, timesSec[nextKey] - nowSeconds),
        progressPercent: Math.min(100, Math.max(0, (elapsed / span) * 100)),
      };
    }
  }

  const tomorrowFajrSec = 86400 + parseTimeToMinutes(nextDayRow.fajr) * 60;
  const span = Math.max(1, tomorrowFajrSec - timesSec.isha);
  const elapsed = nowSeconds - timesSec.isha;
  return {
    activeKey: 'isha',
    nextKey: 'fajr',
    nextTimeFormatted: nextDayRow.fajr,
    isTomorrowFajr: true,
    secondsRemaining: Math.max(0, tomorrowFajrSec - nowSeconds),
    progressPercent: Math.min(100, Math.max(0, (elapsed / span) * 100)),
  };
}
