const PRAYER_CITY_STORAGE_KEY = 'namaz_schedule_city_v1';

export function loadSavedPrayerCity(): PrayerScheduleCityId {
  try {
    if (typeof window === 'undefined') return 'ufa';
    const saved = window.localStorage.getItem(PRAYER_CITY_STORAGE_KEY);
    if (
      saved &&
      PRAYER_SCHEDULE_CITIES.some((c) => c.id === saved)
    ) {
      return saved as PrayerScheduleCityId;
    }
  } catch {
    // ignore storage errors
  }
  return 'ufa';
}

export function savePrayerCity(cityId: PrayerScheduleCityId): void {
  try {
    if (typeof window !== 'undefined') {
      window.localStorage.setItem(PRAYER_CITY_STORAGE_KEY, cityId);
    }
  } catch {
    // ignore storage errors
  }
}

