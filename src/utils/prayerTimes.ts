export type PrayerKey =
  | 'fajr'
  | 'sunrise'
  | 'dhuhr'
  | 'asr'
  | 'maghrib'
  | 'isha';

export type PrayerPeriodId = 'oct_nov' | 'nov_dec';

export interface PrayerTableRow {
  /** Идентификатор периода (таблицы) */
  periodId: PrayerPeriodId;
  /** Номер дня по Хиджре (1–29 или 1–30) */
  hijriDay: number;
  /** Месяц по Миляди (10 = окт, 11 = ноя, 12 = дек) */
  month: number;
  /** День месяца по Миляди */
  day: number;
  /** Отображаемая дата Миләди в таблице (например, "12 окт", "10 ноя", "4 дек") */
  miladiLabel: string;
  /** Полная дата на русском (например, "12 октября", "10 ноября", "4 декабря") */
  miladiFullRu: string;
  /** День недели на татарском из таблицы ("Атна көннәре") */
  weekdayTt: string;
  /** День недели на русском */
  weekdayRu: string;
  /** Пятница (Җомга) */
  isFriday: boolean;
  /** Выделена ли строка ярко-зелёным в оригинальной таблице (пятницы и 10 ноя — начало месяца) */
  isGreenRow: boolean;
  /** Иртәнге намаз (Утренний / Фаджр) */
  fajr: string;
  /** Кояш чыга (Восход / Шурук) */
  sunrise: string;
  /** Өйлә намаз (Полуденный / Зухр) */
  dhuhr: string;
  /** Икенде намаз (Послеполуденный / Аср) */
  asr: string;
  /** Ахшам намаз (Вечерний / Магриб) */
  maghrib: string;
  /** Ястү намаз (Ночной / Иша) */
  isha: string;
}

export interface PrayerItemMeta {
  key: PrayerKey;
  /** Заголовок колонки из таблицы (на татарском) */
  tableTitleTt: string;
  /** Название на русском */
  nameRu: string;
  /** Название на арабском */
  nameAr: string;
  /** Краткое пояснение */
  subtitle: string;
  /** Количество ракаатов */
  rakats: string;
  /** Является ли обязательным намазом (false для Восхода / Кояш чыга) */
  isObligatoryPrayer: boolean;
}

